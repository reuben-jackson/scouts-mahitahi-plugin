import assert from "node:assert/strict";
import "../src/invoice-export.js";
const api = globalThis.mahiTahiInvoices;
const templateText = '*ContactName,EmailAddress,*InvoiceNumber,Reference,*InvoiceDate,*DueDate,Total,InventoryItemCode,*Description,*Quantity,*UnitAmount,Discount,*AccountCode,*TaxType,TrackingName1,TrackingOption1,TrackingName2,TrackingOption2,Currency,BrandingTheme\r\n';
const template = api.readTemplate(templateText);
const sourceText = '\uFEFFBillable Status,Account Name,Start Date,Contact First Name,Contact Last Name,Date of Birth,Role Name,Special Billing Comments,Note 1,Note 2,Family Contact First Name,Family Contact Last Name,Family Contact Email Address,Fees Charged to,National Database Number\r\nBillable,Example Group,01/01/2026,Alex,Example,01/01/2000,Youth,,,,Pat,Example,pat@example.invalid,Family,FAKE001\r\nNot Billable,Example Group,01/01/2026,Jamie,Example,01/01/2000,Youth,,,,Pat,Example,pat@example.invalid,Family,FAKE002\r\nBillable,Example Group,01/01/2026,Alex,Example,01/01/2000,Youth,,,,Pat,Example,pat@example.invalid,Family,FAKE001\r\n';
const source = api.readSource(sourceText);
const mapping = {first:'3',last:'4',familyFirst:'10',familyLast:'11',email:'12',id:'14',status:'0'};
const mapped = api.mapMembers(source, mapping, 'family');
assert.equal(mapped.duplicates, 1);
assert.equal(mapped.members.length, 2);
assert.equal(mapped.members[0].contact, 'Pat Example');
const settings = {description:'Term fee',amount:'140',account:'200',tax:'GST on Income',basis:'inclusive',invoiceDate:'2026-12-25',dueDate:'2027-01-08',prefix:'TEST-',start:'42'};
let result = api.createExport(template, mapped.members, settings);
const records = api.parseCsv(result.csv);
assert.deepEqual(records[0], api.parseCsv(templateText)[0]);
const value = (row, key) => row[template.keys.indexOf(key)];
assert.equal(result.count, 2);
assert.equal(result.total, '280.00');
assert.equal(value(records[1], 'InvoiceNumber'), 'TEST-42');
assert.equal(value(records[2], 'InvoiceNumber'), 'TEST-43');
assert.equal(value(records[1], 'InvoiceDate'), '25/12/2026');
assert.equal(value(records[1], 'DueDate'), '08/01/2027');
assert.equal(value(records[1], 'UnitAmount'), '140.00');
assert.equal(value(records[1], 'Description'), 'Term fee - Alex Example');
assert.equal(value(records[1], 'Total'), '');
assert.equal(value(records[1], 'Currency'), 'NZD');
assert.equal(value(records[2], 'ContactName'), 'Pat Example');
assert.equal(mapped.members[0].contactFirst, 'Pat');
assert.equal(mapped.members[0].contactLast, 'Example');
const myobSettings = {...settings, account:'4-1000', tax:'GST', prefix:'T-', start:'42'};
const myob = api.createMyobExport(mapped.members, myobSettings);
const myobRecords = api.parseCsv(myob.csv);
assert.deepEqual(myobRecords[0], ['Co./Last Name','First Name','Invoice #','Date','Inclusive','Delivery Status','Description','Account No.','Amount','GST Code','Sale Status','Terms - Payment is Due','Terms - Discount Days','Terms - Balance Due Days']);
assert.equal(myobRecords[1][0], 'Example');
assert.equal(myobRecords[1][1], 'Pat');
assert.equal(myobRecords[1][2], 'T-42');
assert.equal(myobRecords[1][4], 'X');
assert.equal(myobRecords[1][7], '4-1000');
assert.equal(myobRecords[1][13], '14');
assert.equal(myob.count, 2);
assert.match(myob.csv, /\r\n\r\n/);
const issuer = {name:'Example Scout Group',gstNumber:'123-456-789',gstRate:'15',contact:'1 Example Street\nExampletown',payment:'Pay by bank transfer.',footer:'Thank you.'};
const documents = api.createInvoiceDocuments(mapped.members, settings, issuer);
assert.equal(documents.count, 2);
assert.equal(documents.total, '280.00');
assert.match(documents.html, /<!doctype html>/);
assert.match(documents.html, /GST \(15%\)/);
assert.match(documents.html, /NZD 18\.26/);
assert.match(documents.text, /SUBJECT: Invoice TEST-42 from Example Scout Group/);
assert.match(documents.text, /------------------------------------------------------------------------/);
assert.match(api.createInvoiceDocuments(mapped.members, settings, {...issuer, name:'Example <Group>'}).html, /Example &lt;Group&gt;/);
mapped.members[1].selected = false;
assert.equal(api.createExport(template, mapped.members, settings).total, '140.00');
assert.deepEqual(api.parseCsv('a,b\r\n"comma, quote "" test","line\nnext"'), [['a','b'],['comma, quote " test','line\nnext']]);
assert.throws(() => api.parseCsv('"unclosed'), /Unclosed/);
assert.throws(() => api.parseCsv('"closed"x'), /Unexpected/);
assert.throws(() => api.readSource('a,b\n1'), /wrong number/);
assert.throws(() => api.readSource('a,a\n1,2'), /duplicate/);
assert.throws(() => api.readTemplate('ContactName,InvoiceNumber'), /missing/);
assert.throws(() => api.xeroDate('2026-02-29'), /valid/);
assert.equal(api.xeroDate('2028-02-29'), '29/02/2028');
assert.equal(api.daysBetween('2026-12-25', '2027-01-08'), 14);
for (const change of [{amount:'-1'}, {amount:'140.001'}, {amount:'1e4'}, {amount:'9'.repeat(400)}, {account:''}, {tax:''}, {start:'0'}, {dueDate:'2026-01-01'}, {basis:''}, {prefix:''}, {description:'=BAD()'}]) {
    assert.throws(() => api.createExport(template, mapped.members, {...settings, ...change}));
}
for (const change of [{account:'4000'}, {tax:'TOOLONG'}, {prefix:'TOO-LONG-'}, {dueDate:'2030-01-01'}]) {
    assert.throws(() => api.createMyobExport(mapped.members, {...myobSettings, ...change}));
}
for (const badIssuer of [{...issuer,name:''}, {...issuer,gstNumber:''}, {...issuer,gstRate:'101'}]) {
    assert.throws(() => api.createInvoiceDocuments(mapped.members, settings, badIssuer));
}
const conflict = api.readSource(sourceText.replace('Billable,Example Group,01/01/2026,Alex,Example,01/01/2000,Youth,,,,Pat,Example,pat@example.invalid,Family,FAKE001\r\n', 'Billable,Example Group,01/01/2026,Alex,Example,01/01/2000,Youth,,,,Other,Example,other@example.invalid,Family,FAKE001\r\n'));
assert.throws(() => api.mapMembers(conflict, mapping, 'family'), /Conflicting/);
mapped.members[0].contact = '=BAD()';
assert.throws(() => api.createExport(template, mapped.members, settings), /formula/);
mapped.members[0].contact = 'Example, Pat';
assert.equal(value(api.parseCsv(api.createExport(template, mapped.members, settings).csv)[1], 'ContactName'), 'Example, Pat');
console.log('Invoice conversion tests passed: Xero and MYOB formats, names, duplicates, dates, amounts, selection and validation.');
