import assert from "node:assert/strict";
import "../src/invoice-export.js";
const api = globalThis.mahiTahiInvoices;
const templateText = '*ContactName,EmailAddress,*InvoiceNumber,Reference,*InvoiceDate,*DueDate,Total,InventoryItemCode,*Description,*Quantity,*UnitAmount,Discount,*AccountCode,*TaxType,TrackingName1,TrackingOption1,TrackingName2,TrackingOption2,Currency,BrandingTheme\r\n';
const template = api.readTemplate(templateText);
const sourceText = '\uFEFFFirst Name,Last Name,Family Contact First Name,Family Contact Last Name,Family Contact Email Address,National Database Number,Billable Status\r\nAlex,Example,Pat,Example,pat@example.invalid,FAKE001,Billable\r\nJamie,Example,Pat,Example,pat@example.invalid,FAKE002,Not Billable\r\nAlex,Example,Pat,Example,pat@example.invalid,FAKE001,Billable\r\n';
const source = api.readSource(sourceText);
const mapping = {first:'0',last:'1',familyFirst:'2',familyLast:'3',email:'4',id:'5',status:'6'};
const mapped = api.mapMembers(source, mapping, 'family');
assert.equal(mapped.duplicates, 1);
assert.equal(mapped.members.length, 2);
assert.equal(mapped.members[0].contact, 'Pat Example');
const settings = {description:'Term fee',amount:'140',account:'200',tax:'GST on Income',basis:'inclusive',invoiceDate:'2026-12-25',dueDate:'2027-01-08',prefix:'TEST-',start:'42'};
let result = api.createExport(template, mapped.members, settings);
const records = api.parseCsv(result.csv);
assert.deepEqual(records[0], api.parseCsv(templateText)[0]);
const value = (row, key) => row[template.keys.indexOf(key)];
assert.equal(result.count, 2);
assert.equal(result.total, '280.00');
assert.equal(value(records[1], 'InvoiceNumber'), 'TEST-42');
assert.equal(value(records[2], 'InvoiceNumber'), 'TEST-43');
assert.equal(value(records[1], 'InvoiceDate'), '25/12/2026');
assert.equal(value(records[1], 'DueDate'), '08/01/2027');
assert.equal(value(records[1], 'UnitAmount'), '140.00');
assert.equal(value(records[1], 'Description'), 'Term fee - Alex Example');
assert.equal(value(records[1], 'Total'), '');
assert.equal(value(records[1], 'Currency'), 'NZD');
assert.equal(value(records[2], 'ContactName'), 'Pat Example');
mapped.members[1].selected = false;
assert.equal(api.createExport(template, mapped.members, settings).total, '140.00');
assert.deepEqual(api.parseCsv('a,b\r\n"comma, quote "" test","line\nnext"'), [['a','b'],['comma, quote " test','line\nnext']]);
assert.throws(() => api.parseCsv('"unclosed'), /Unclosed/);
assert.throws(() => api.parseCsv('"closed"x'), /Unexpected/);
assert.throws(() => api.readSource('a,b\n1'), /wrong number/);
assert.throws(() => api.readSource('a,a\n1,2'), /duplicate/);
assert.throws(() => api.readTemplate('ContactName,InvoiceNumber'), /missing/);
assert.throws(() => api.xeroDate('2026-02-29'), /valid/);
assert.equal(api.xeroDate('2028-02-29'), '29/02/2028');
for (const change of [{amount:'-1'}, {amount:'140.001'}, {amount:'1e4'}, {amount:'9'.repeat(400)}, {account:''}, {tax:''}, {start:'0'}, {dueDate:'2026-01-01'}, {basis:''}, {prefix:''}, {description:'=BAD()'}]) {
    assert.throws(() => api.createExport(template, mapped.members, {...settings, ...change}));
}
const conflict = api.readSource(sourceText.replace('Alex,Example,Pat,Example,pat@example.invalid,FAKE001,Billable\r\n', 'Alex,Example,Other,Example,other@example.invalid,FAKE001,Billable\r\n'));
assert.throws(() => api.mapMembers(conflict, mapping, 'family'), /Conflicting/);
mapped.members[0].contact = '=BAD()';
assert.throws(() => api.createExport(template, mapped.members, settings), /formula/);
mapped.members[0].contact = 'Example, Pat';
assert.equal(value(api.parseCsv(api.createExport(template, mapped.members, settings).csv)[1], 'ContactName'), 'Example, Pat');
console.log('Invoice conversion tests passed: CSV, template preservation, names, duplicates, dates, amounts, selection and validation.');
